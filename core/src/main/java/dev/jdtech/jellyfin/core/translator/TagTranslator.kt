/**
 * 把分类 / 标签里的日文、英文值翻成简体中文。
 *
 * 与 [MetadataTranslator] 的区别：对面是「很多很短的值」而不是「一两段长文本」，因此
 * 先查内置词典、命中就不发请求；只有含假名的值才交给大模型，纯英文一律保留原值
 * （TMDB 的关键词交给模型会译出五花八门的结果）。词表与策略参照 JavSP 的 `javsp/tag.py`。
 */
interface TagTranslator {
    /** 该值是否有译文可翻：词典收录，或含假名（日文原文）。 */
    fun needsTranslation(value: String): Boolean

    /**
     * 批量翻译，返回「原值 → 译文」的结果，**只包含确实拿到译文的值**。
     *
     * 词典与本地缓存命中的值不会产生网络请求；整批里需要模型翻译的值合成一次请求。
     * 请求失败时不抛异常，而是把异常放进 [TagTranslationResult.error]，已命中的译文照常返回，
     * 由调用方决定是只让未知词保留原文，还是停掉本轮剩余的翻译。
     */
    suspend fun translate(values: Collection<String>): TagTranslationResult
}

