    /** 是否属于无需翻译的技术特征 / 缩写。 */
    fun isSkipValue(value: String): Boolean = value.trim().uppercase() in SKIP_VALUES

    /** 查词典，没有时返回 null。 */
    fun lookup(value: String): String? {
        val trimmed = value.trim()
        if (trimmed.isEmpty()) return null
        // 站点分类常是繁体，词典键以简体 / 日文原样为主，因此再拿繁→简后的形态查一次
        val simplified = MetadataTagNormalizer.toSimplified(trimmed)
        return JA_GLOSSARY[trimmed]
            ?: JA_GLOSSARY[simplified]
            ?: EN_MAP[trimmed.lowercase()]
            ?: EN_MAP[simplified.lowercase()]
    }
